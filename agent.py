# agents.py - 3 AI Agents
class CleanerAgent:
    def run(self, data):
        print("Cleaner Agent: Cleaning data...")
        cleaned = [row.strip().lower() for row in data if row.strip() != ""]
        return cleaned

class AnalystAgent:
    def run(self, cleaned_data):
        print("Analyst Agent: Analyzing data...")
        total = len(cleaned_data)
        result = f"Total Records: {total}\nSample Data: {cleaned_data[:3]}"
        return result

class ReporterAgent:
    def run(self, analysis):
        print("Reporter Agent: Creating report...")
        report = f"--- ENTERPRISE REPORT ---\n{analysis}\nStatus: Success\nGenerated by Multi-Agent System"
        return report
